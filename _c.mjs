import { chromium } from '@playwright/test';
const SP = process.argv[2], tag = process.argv[3];
const b = await chromium.launch({ headless:true, args:['--use-angle=d3d11', '--ignore-gpu-blocklist', '--enable-gpu', '--force_high_performance_gpu'] });
const p = await b.newPage({ viewport:{ width:1400, height:1000 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:5199/'); await p.waitForTimeout(2500);
await p.getByRole('button', { name:'Purple (dyed)' }).click(); await p.waitForTimeout(600);
await p.locator('#expand').click(); await p.waitForTimeout(600);
const v = async (yaw, pitch, zoom, look, n) => { await p.evaluate(([y, pi, z, l]) => Object.assign(window.__V, { yaw:y, pitch:pi, zoom:z, look:l, targetYaw:null, dirty:true }), [yaw, pitch, zoom, look]); await p.waitForTimeout(900); await p.screenshot({ path: `${SP}/${tag}-${n}.png` }); };
await v(-0.4, 0.6, 0.5, [0, 0.25], 'top');
await v(-0.25, 0.2, 0.45, [0, 0.22], 'front');
await v(Math.PI - 0.3, 0.3, 0.45, [0, 0.25], 'back');
await v(Math.PI/2 + 0.5, 0.1, 0.4, [0.05, 0.15], 'shoulderR');
await v(-Math.PI/2 - 0.5, 0.1, 0.4, [-0.05, 0.15], 'shoulderL');
await v(-0.5, 0.08, 1, [0, 0], 'full');
console.log('errors', JSON.stringify(errs));
await b.close();
